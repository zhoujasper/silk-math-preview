// Build-time only: extract names and glyphs from the pinned MathJax dependency.
// No parser or renderer code is imported by the completion provider at runtime.
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { MapHandler } = require('@mathjax/src/js/input/tex/MapHandler.js');
const packages = {
  base: ['base/BaseConfiguration', 'BaseConfiguration'],
  ams: ['ams/AmsConfiguration', 'AmsConfiguration'],
  mathtools: ['mathtools/MathtoolsConfiguration', 'MathtoolsConfiguration'],
  physics: ['physics/PhysicsConfiguration', 'PhysicsConfiguration'],
  braket: ['braket/BraketConfiguration', 'BraketConfiguration'],
  upgreek: ['upgreek/UpgreekConfiguration', 'UpgreekConfiguration'],
  cancel: ['cancel/CancelConfiguration', 'CancelConfiguration'],
  boldsymbol: ['boldsymbol/BoldsymbolConfiguration', 'BoldsymbolConfiguration'],
  color: ['color/ColorConfiguration', 'ColorConfiguration'],
};
const output = [];
for (const [pkg, [file, exported]] of Object.entries(packages)) {
  const config = require(`@mathjax/src/js/input/tex/${file}.js`)[exported];
  const names = new Map();
  for (const name of config.handler.macro ?? []) {
    const map = MapHandler.getMap(name);
    if (!(map?.map instanceof Map)) throw new Error(`MathJax map layout changed: ${name}`);
    for (const [raw, value] of map.map) {
      const command = raw.replace(/^\\/, '');
      if (!/^[A-Za-z@]+$/.test(command)) continue;
      // Only infer arity when the actual parser method has an unambiguous shape.
      const method = value.func?.name;
      const arity = ['MathFont', 'Accent', 'UnderOver', 'HBox', 'Boldsymbol', 'Cancel', 'ColorBox'].includes(method) ? 1
        : ['Frac', 'Overset', 'Underset', 'StackRel'].includes(method) ? 2
        : method === 'Macro' && Number.isInteger(value.args?.[1]) ? value.args[1] : 0;
      names.set(command, [command, value.char ?? '', arity]);
    }
  }
  output.push([pkg, [...names.values()].sort((a, b) => a[0].localeCompare(b[0], 'en'))]);
}
const source = '// Generated by scripts/generate-completion-symbols.mjs from MathJax 4.1.3.\n'
  + '// Copyright (c) 2017-2026 The MathJax Consortium. Apache-2.0; see THIRD_PARTY_NOTICES.md.\n'
  + '// Color mappings: Copyright (c) 2018-2026 Omar Al-Ithawi and The MathJax Consortium.\n'
  + 'export const SYMBOL_PACKAGES: readonly (readonly [string, readonly (readonly [string, string, number])[]])[] = '
  + JSON.stringify(output, null, 2) + ';\n';
const file = new URL('../src/completion/symbols.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(file, 'utf8') !== source) throw new Error('Completion symbols need regeneration');
} else {
  await mkdir(new URL('../src/completion/', import.meta.url), { recursive: true });
  await writeFile(file, source);
}
console.log(JSON.stringify({ packages: output.length, entries: output.reduce((n, [, entries]) => n + entries.length, 0) }));
